#!/usr/bin/env python3
"""Zero-dependency protobuf wire-format decoder for `build/zisk.pilout`.

Reader half of the extractor round-trip gate (issue #303). Hand-rolled from the
wire format rather than generated by `protoc`, for two reasons: the checker must
run on a bare `python3` with nothing installed, and a decoder sharing no code
with the Rust `prost` decoder the extractor uses cannot share a bug with it, so
a decode-side distortion cannot cancel against an extraction-side one.

Wire format, in full: a message body is a sequence of records, each a varint key
`(field_number << 3) | wire_type` followed by a payload whose shape depends on
the wire type -- 0 varint, 1 fixed 64-bit, 2 length-delimited (a varint byte
count then that many bytes), 5 fixed 32-bit. Wire types 3 and 4 (proto2 groups)
are not emitted by proto3 and are rejected. That is the whole generic layer: it
yields `field_number -> [raw value]`, an `int` for wire types 0/1/5 and `bytes`
for wire type 2, dropping no field number, including undeclared ones.

Decisions the wire format itself does not determine:

* Field meaning comes from tables transcribed by hand from
  `tools/pil-extract/proto/pilout.proto`. The "known" set per message is *every*
  field number that .proto declares, not just the ones read here, so an entry in
  `PilOut.unknown_fields()` means the file carries data this tree's schema does
  not describe -- drift the gate must surface, not swallow.
* proto3 omits scalars holding the default, so an absent scalar reads back as
  0 / b"" / "". Repeated numeric fields may be packed (one length-delimited blob
  of back-to-back varints) or unpacked (one record each); which one a writer
  chose is not something a reader may assume, so both are accepted.
* `sint32` fields are zigzag-encoded: signed n travels as `(n << 1) ^ (n >> 31)`.
  Read as a plain varint it yields a wrong, always non-negative number. The
  zigzag fields are exactly the four `rowOffset`s listed in `ZIGZAG_FIELDS` --
  precisely what separates a current-row reference from a next-row one, so
  misreading them would quietly invalidate the whole round-trip.
* `PilOut.baseField` is bytes with no declared byte order, so the order is
  calibrated from the file: whichever of the big- and little-endian readings
  equals the Goldilocks characteristic wins, and loading fails if neither does.
  `base_field_calibration` also reports whether the two readings differ, i.e.
  whether the test discriminates at all. The calibrated order is then what
  `decode_constant` applies to `Operand.Constant.value`.

Public API: `load(path) -> PilOut`; `PilOut.airs()`, `.num_challenges`,
`.base_field_prime`, `.base_field_byte_order`, `.symbols`, `.decode_constant()`,
`.unknown_fields()`; `Air.constraints/.expressions/.stage_widths/...`;
`Constraint.kind/.expression_idx/.debug_line/.offset_min/.offset_max`.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

GOLDILOCKS_PRIME = (1 << 64) - (1 << 32) + 1

WIRE_VARINT = 0
WIRE_64BIT = 1
WIRE_LEN = 2
WIRE_32BIT = 5


class WireFormatError(Exception):
    """The byte stream is not well-formed protobuf."""


class SchemaError(Exception):
    """The bytes decode, but do not fit the transcribed .proto schema."""


# ---------------------------------------------------------------- wire layer


def read_varint(buf: bytes, pos: int) -> tuple[int, int]:
    """Read a base-128 varint at `pos`; return (value, next position)."""
    result = 0
    shift = 0
    start = pos
    while True:
        if pos >= len(buf):
            raise WireFormatError(f"truncated varint at offset {start}")
        byte = buf[pos]
        pos += 1
        result |= (byte & 0x7F) << shift
        if byte < 0x80:
            return result, pos
        shift += 7
        if shift > 63:
            raise WireFormatError(f"varint exceeds 10 bytes at offset {start}")


def zigzag_decode(value: int) -> int:
    """Undo zigzag encoding; used by the sint32 fields only."""
    return (value >> 1) ^ -(value & 1)


def unpack_varints(blob: bytes) -> list[int]:
    """Read a packed repeated numeric field: back-to-back varints."""
    out: list[int] = []
    pos = 0
    while pos < len(blob):
        value, pos = read_varint(blob, pos)
        out.append(value)
    return out


def decode_message(buf: bytes) -> dict[int, list[int | bytes]]:
    """Split a message body into field_number -> [raw value], keeping unknowns."""
    fields: dict[int, list[int | bytes]] = {}
    pos = 0
    size = len(buf)
    while pos < size:
        key, pos = read_varint(buf, pos)
        field_num = key >> 3
        wire_type = key & 0x07
        if field_num == 0:
            raise WireFormatError(f"field number 0 at offset {pos}")
        value: int | bytes
        if wire_type == WIRE_VARINT:
            value, pos = read_varint(buf, pos)
        elif wire_type == WIRE_LEN:
            length, pos = read_varint(buf, pos)
            if pos + length > size:
                raise WireFormatError(f"truncated length-delimited field at offset {pos}")
            value = buf[pos : pos + length]
            pos += length
        elif wire_type in (WIRE_64BIT, WIRE_32BIT):
            width = 8 if wire_type == WIRE_64BIT else 4
            if pos + width > size:
                raise WireFormatError(f"truncated {width * 8}-bit field at offset {pos}")
            value = int.from_bytes(buf[pos : pos + width], "little")
            pos += width
        else:
            raise WireFormatError(f"unsupported wire type {wire_type} at offset {pos}")
        fields.setdefault(field_num, []).append(value)
    return fields


# -------------------------------------------------------------- schema layer


@dataclass
class Calibration:
    """Result of deciding `baseField`'s byte order from the file itself."""

    byte_order: str
    prime: int
    big_reading: int
    little_reading: int
    discriminates: bool
    raw: bytes


def base_field_calibration(base_field: bytes) -> Calibration:
    """Report which endianness of `baseField` yields the Goldilocks prime."""
    big = int.from_bytes(base_field, "big")
    little = int.from_bytes(base_field, "little")
    matches = [name for name, v in (("big", big), ("little", little)) if v == GOLDILOCKS_PRIME]
    if not matches:
        raise SchemaError(
            f"baseField {base_field.hex()} is neither big-endian ({big}) nor little-endian "
            f"({little}) equal to Goldilocks {GOLDILOCKS_PRIME}"
        )
    return Calibration(matches[0], GOLDILOCKS_PRIME, big, little, big != little, base_field)


class ParseContext:
    """Byte order, prime, and the running record of undeclared field numbers."""

    def __init__(self, calibration: Calibration) -> None:
        self.calibration = calibration
        self.byte_order = calibration.byte_order
        self.prime = calibration.prime
        self.unknown: dict[tuple[str, int], int] = {}

    def note_unknown(self, message: str, field_num: int) -> None:
        key = (message, field_num)
        self.unknown[key] = self.unknown.get(key, 0) + 1

    def decode_constant(self, blob: bytes) -> int:
        """Interpret `Operand.Constant.value` with the calibrated byte order.

        A field element arrives already reduced, so the range check is the
        stronger statement and reduction mod p is a no-op on anything passing
        it. An out-of-range constant is a decode failure, not something to fold
        quietly back into range.
        """
        value = int.from_bytes(blob, self.byte_order)
        if value >= self.prime:
            raise SchemaError(f"constant {blob.hex()} decodes to {value} >= p")
        return value


class View:
    """A decoded message body plus the field numbers its .proto declares."""

    __slots__ = ("ctx", "message", "fields")

    def __init__(
        self,
        ctx: ParseContext,
        message: str,
        body: bytes | dict[int, list[int | bytes]],
        known: Iterable[int],
    ) -> None:
        self.ctx = ctx
        self.message = message
        self.fields = decode_message(body) if isinstance(body, bytes) else body
        declared = set(known)
        for field_num in self.fields:
            if field_num not in declared:
                ctx.note_unknown(message, field_num)

    def has(self, num: int) -> bool:
        return num in self.fields

    def _last(self, num: int, numeric: bool, default):
        """Last occurrence of field `num` (the proto3 merge rule), type-checked."""
        values = self.fields.get(num)
        if not values:
            return default
        value = values[-1]
        if isinstance(value, int) is not numeric:
            raise SchemaError(
                f"{self.message} field {num}: expected {'numeric' if numeric else 'bytes'}"
            )
        return value

    def scalar_int(self, num: int, default: int = 0) -> int:
        return self._last(num, True, default)

    def scalar_sint(self, num: int, default: int = 0) -> int:
        raw = self._last(num, True, None)
        return default if raw is None else zigzag_decode(raw)

    def scalar_bytes(self, num: int, default: bytes = b"") -> bytes:
        return self._last(num, False, default)

    def scalar_str(self, num: int, default: str = "") -> str:
        raw = self._last(num, False, None)
        return default if raw is None else raw.decode("utf-8")

    def submessage(self, num: int) -> bytes | None:
        """A singular submessage field, refusing the repeated-occurrence case.

        proto3 says repeated occurrences of a singular submessage field *merge*;
        `_last` would take the last one instead. Rather than implement a merge
        rule no writer here exercises, and rather than diverge silently from the
        `prost` decoder the extractor uses, refuse: two occurrences of a
        singular submessage mean this reader and that one would disagree.
        """
        values = self.fields.get(num)
        if values and len(values) > 1:
            raise SchemaError(
                f"{self.message} field {num}: {len(values)} occurrences of a singular "
                f"submessage; proto3 merges these and this decoder does not"
            )
        return self._last(num, False, None)

    def repeated_uint(self, num: int) -> list[int]:
        """Repeated numeric field, accepting both packed and unpacked encodings."""
        out: list[int] = []
        for value in self.fields.get(num, []):
            out.append(value) if isinstance(value, int) else out.extend(unpack_varints(value))
        return out

    def repeated_bytes(self, num: int) -> list[bytes]:
        out: list[bytes] = []
        for value in self.fields.get(num, []):
            if isinstance(value, int):
                raise SchemaError(f"{self.message} field {num}: expected bytes")
            out.append(value)
        return out


