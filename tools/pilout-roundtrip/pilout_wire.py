def _main(argv: list[str]) -> int:
    default = Path(__file__).resolve().parents[2] / "build" / "zisk.pilout"
    path = Path(argv[1]) if len(argv) > 1 else default
    pilout = load(path)
    cal = pilout.calibration
    print(
        f"file                {path}\n"
        f"pilout name         {pilout.name!r}\n"
        f"baseField bytes     {cal.raw.hex()}\n"
        f"  big-endian        {cal.big_reading}\n"
        f"  little-endian     {cal.little_reading}\n"
        f"  goldilocks p      {GOLDILOCKS_PRIME}\n"
        f"calibrated order    {cal.byte_order}\n"
        f"calibration discriminates: {cal.discriminates}\n"
        f"prime               {pilout.base_field_prime}\n"
        f"numChallenges       {pilout.num_challenges}\n"
        f"numPublicValues     {pilout.num_public_values}\n"
        f"globals             expressions={pilout.num_global_expressions}"
        f" constraints={pilout.num_global_constraints} hints={pilout.num_hints}"
        f" publicTables={pilout.num_public_tables} symbols={len(pilout.symbols)}\n"
    )

    row = "{:<10} {:>3} {:<20} {:>6} {:>7} {:>7} {:>6} {:>5} {:>6} {:>6} {:>7}"
    header = row.format(
        "airgroup", "idx", "air", "cons", "exprs", "every", "first", "last", "frame",
        "fixed", "airval",
    )
    print(header)
    print("-" * len(header))
    totals = {kind: 0 for kind, _, _ in CONSTRAINT_KINDS.values()}
    total_cons = 0
    total_exprs = 0
    for ref in pilout.airs():
        counts = ref.air.kind_counts()
        for kind, count in counts.items():
            totals[kind] += count
        total_cons += len(ref.air.constraints)
        total_exprs += len(ref.air.expressions)
        print(row.format(
            ref.airgroup_name, ref.air_idx, ref.air_name,
            len(ref.air.constraints), len(ref.air.expressions),
            counts["every_row"], counts["first_row"], counts["last_row"],
            counts["every_frame"], ref.air.num_fixed_cols, ref.air.num_air_values,
        ))
    print("-" * len(header))
    print(row.format(
        "TOTAL", "", f"{len(pilout.airs())} airs", total_cons, total_exprs,
        totals["every_row"], totals["first_row"], totals["last_row"], totals["every_frame"], "", "",
    ))

    unusual = [
        (ref, i, c)
        for ref in pilout.airs()
        for i, c in enumerate(ref.air.constraints)
        if c.kind != "every_row"
    ]
    print(f"\nnon-every_row constraints: {len(unusual)}")
    for ref, i, constraint in unusual:
        frame = ""
        if constraint.kind == "every_frame":
            frame = f" offsets=[{constraint.offset_min},{constraint.offset_max}]"
        print(
            f"  {ref.airgroup_name}/{ref.air_name}[{ref.air_idx}] #{i} {constraint.kind}"
            f" expr={constraint.expression_idx}{frame} debugLine={constraint.debug_line!r}"
        )

    unknown = pilout.unknown_fields()
    print(f"unknown field numbers: {len(unknown)}")
    for message, field_num, count in unknown:
        print(f"  {message} field {field_num} x{count}")
    return 0


if __name__ == "__main__":
    sys.exit(_main(sys.argv))
