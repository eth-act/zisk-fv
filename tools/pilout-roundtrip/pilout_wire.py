class PilOut:
    def __init__(self, data: bytes, path: str | None = None) -> None:
        root = decode_message(data)
        base_field = root.get(2, [b""])[-1]
        if not isinstance(base_field, bytes):
            raise SchemaError("PilOut.baseField is not length-delimited")
        self.calibration = base_field_calibration(base_field)
        self.ctx = ParseContext(self.calibration)
        self.path = path
        view = View(self.ctx, "PilOut", root, PILOUT_FIELDS)
        self.name = view.scalar_str(1)
        self.air_groups = [AirGroup(self.ctx, b) for b in view.repeated_bytes(3)]
        self.num_challenges = view.repeated_uint(4)
        self.num_proof_values = view.repeated_uint(5)
        self.num_public_values = view.scalar_int(6)
        self.num_public_tables = len(view.repeated_bytes(7))
        self.num_global_expressions = len(view.repeated_bytes(8))
        self.global_constraints = [GlobalConstraint(self.ctx, b) for b in view.repeated_bytes(9)]
        self.num_hints = len(view.repeated_bytes(10))
        self.symbols = [Symbol(self.ctx, b) for b in view.repeated_bytes(11)]

    @property
    def num_global_constraints(self) -> int:
        return len(self.global_constraints)

    @property
    def base_field_prime(self) -> int:
        return self.calibration.prime

    @property
    def base_field_byte_order(self) -> str:
        return self.calibration.byte_order

    def decode_constant(self, blob: bytes) -> int:
        return self.ctx.decode_constant(blob)

    def airs(self) -> list[AirRef]:
        return [
            AirRef(group.name, group_idx, air.name, air_idx, air)
            for group_idx, group in enumerate(self.air_groups)
            for air_idx, air in enumerate(group.airs)
        ]

    def unknown_fields(self) -> list[tuple[str, int, int]]:
        """Undeclared (message, field number, occurrences), sorted for reporting."""
        return sorted((msg, num, count) for (msg, num), count in self.ctx.unknown.items())


def load(path: str | Path) -> PilOut:
    path = Path(path)
    return PilOut(path.read_bytes(), str(path))


